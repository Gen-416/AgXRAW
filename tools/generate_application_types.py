"""Generate the desktop request contract from the Python application schema."""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from dngscan.application.contracts import API_VERSION, JOB_FIELDS, COMMANDS, CALIBRATION_COMMANDS


def content():
    types = {'string': 'string', 'number': 'number', 'integer': 'number',
             'boolean': 'boolean', 'number-or-auto': 'number | "auto"',
             'object': 'Record<string, Json>'}
    fields = '\n'.join(f'  {key}?: {types[value]};' for key, value in JOB_FIELDS.items())
    commands = ' | '.join(f'"{name}"' for name in COMMANDS | CALIBRATION_COMMANDS)
    return f'''// Generated by tools/generate_application_types.py; do not edit.
export const API_VERSION = {API_VERSION} as const;
export type Json = string | number | boolean | null | Json[] | {{ [key: string]: Json }};
export type Command = {commands};
export interface JobParams {{
{fields}
}}
export interface Bootstrap {{
  version: typeof API_VERSION;
  defaults: JobParams;
  commands: Command[];
  default_directory: string;
  raw_extensions: string[];
  session_token: string;
  initial_source?: string;
  capabilities: {{ coreimage: boolean; hdr: boolean; hdr_reason: string;
    dependency_errors: string[] }};
}}
export interface Request {{
  version: typeof API_VERSION;
  id: string;
  command: Command;
  params: JobParams | Record<string, Json>;
}}
export type Reply = {{ version: typeof API_VERSION; id: string; ok: true; result: Result }}
  | {{ version: typeof API_VERSION; id: string | null; ok: false;
      error: {{ code: string; message: string }} }};
// Diagnostics remain extensible. Fields consumed by this frontend are
// checked at the response boundary in client.ts, not trusted by a cast.
export interface Result {{
  [key: string]: unknown;
  ok: boolean;
  superseded?: boolean;
  generation?: number;
  preview?: string;
  ev?: number;
  ev_auto?: {{ planning_status?: string; anchor_ev?: number }} | null;
  decoder?: string;
  decoder_version?: string | null;
  width?: number;
  height?: number;
  detected?: Record<string, unknown> | null;
  saved?: string[];
  support_lines?: string[];
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'desktop/src/api/generated.ts'
    if args.check:
        if not path.is_file() or path.read_text() != content():
            parser.exit(1, 'Application TypeScript contract is stale; regenerate it.\n')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content())
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
